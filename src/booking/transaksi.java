private void tampilDetail() {
    int baris = tabelTransaksi.getSelectedRow();

    if (baris == -1) {
        JOptionPane.showMessageDialog(this,
            "Pilih transaksi terlebih dahulu!");
        return;
    }

    String detail =
        "ID Booking: " + tabelTransaksi.getValueAt(baris, 0)
        + "\nNama Penyewa: " + tabelTransaksi.getValueAt(baris, 1)
        + "\nNo HP: " + tabelTransaksi.getValueAt(baris, 2)
        + "\nLapangan: " + tabelTransaksi.getValueAt(baris, 3)
        + "\nTanggal: " + tabelTransaksi.getValueAt(baris, 4)
        + "\nTotal Biaya: Rp" + tabelTransaksi.getValueAt(baris, 5)
        + "\nMetode: " + tabelTransaksi.getValueAt(baris, 6)
        + "\nDibayar: Rp" + tabelTransaksi.getValueAt(baris, 7)
        + "\nSisa: Rp" + tabelTransaksi.getValueAt(baris, 8);

    JOptionPane.showMessageDialog(this, detail,
        "Detail Transaksi", JOptionPane.INFORMATION_MESSAGE);
}

 
    
    
private void tampilTransaksi() {
    DefaultTableModel model = new DefaultTableModel(
        new String[]{
            "ID", "Nama Penyewa", "No HP", "Lapangan",
            "Tanggal", "Total Biaya", "Metode",
            "Dibayar", "Sisa Pembayaran"
        }, 0
    );

    String sql = "SELECT id_booking, nama_penyewa, no_hp, "
        + "nama_lapangan, tanggal_booking, total_biaya, "
        + "metode_pembayaran, jumlah_dibayar, sisa_pembayaran "
        + "FROM booking ORDER BY id_booking DESC";

    try (Connection conn = DriverManager.getConnection(
            "jdbc:mysql://localhost:3306/db_futsal",
            "root", "");
         PreparedStatement ps = conn.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id_booking"),
                rs.getString("nama_penyewa"),
                rs.getString("no_hp"),
                rs.getString("nama_lapangan"),
                rs.getDate("tanggal_booking"),
                rs.getDouble("total_biaya"),
                rs.getString("metode_pembayaran"),
                rs.getDouble("jumlah_dibayar"),
                rs.getDouble("sisa_pembayaran")
            });
        }

        tabelTransaksi.setModel(model);

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Gagal memuat transaksi: " + e.getMessage());
    }
}


