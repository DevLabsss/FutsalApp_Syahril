    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
    String lapangan = (String) jComboBox1.getSelectedItem();
    String nama = jTextField1.getText().trim();
    String noHp = jTextField2.getText().trim();
    String metode = (String) comboPembayaran.getSelectedItem();

    if (lapangan == null || nama.isEmpty() || noHp.isEmpty()
            || jDateChooser1.getDate() == null
            || metode == null || textTotal.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Semua data booking dan pembayaran harus diisi!");
        jComboBox1.setSelectedIndex(-1);
        lblStatus.setText("");

        jTextField1.setText("");
        jTextField2.setText("");
        jDateChooser1.setDate(null);

        textTotal.setText("");
        textDP.setText("");
        textSisa.setText("");

        comboPembayaran.setSelectedIndex(-1);
        return;
    }

    double total, dibayar, sisa;

    try {
        total = Double.parseDouble(textTotal.getText().trim());

        if (total <= 0) {
            JOptionPane.showMessageDialog(this,
                "Total biaya harus lebih dari 0!");
            return;
        }

        if (metode.toLowerCase().contains("dp")) {
            dibayar = total * 0.5;
        } else {
            dibayar = total;
        }

        sisa = total - dibayar;

        textDP.setText(String.format("%.0f", dibayar));
        textSisa.setText(String.format("%.0f", sisa));

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
            "Total biaya harus berupa angka!");
        return;
    }

    String url = "jdbc:mysql://localhost:3306/db_futsal";

    try (java.sql.Connection conn =
            java.sql.DriverManager.getConnection(url, "root", "")) {

        String sqlCek = "SELECT id, status FROM lapangan "
                + "WHERE nama_lapangan = ?";

        int idLapangan;

        try (java.sql.PreparedStatement psCek =
                conn.prepareStatement(sqlCek)) {

            psCek.setString(1, lapangan);

            try (java.sql.ResultSet rs = psCek.executeQuery()) {
                if (!rs.next()) {
                    JOptionPane.showMessageDialog(this,
                        "Lapangan tidak ditemukan!");
                    return;
                }

                idLapangan = rs.getInt("id");
                String status = rs.getString("status");

                if (status == null ||
                        !status.trim().equalsIgnoreCase("Tersedia")) {
                    JOptionPane.showMessageDialog(this,
                        "Lapangan tidak tersedia!",
                        "Peringatan",
                        JOptionPane.WARNING_MESSAGE);
                    return;
                }
            }
        }

        String sqlInsert = "INSERT INTO booking "
                + "(id_lapangan, nama_lapangan, nama_penyewa, "
                + "no_hp, tanggal_booking, total_biaya, "
                + "metode_pembayaran, jumlah_dibayar, sisa_pembayaran) "
                + "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)";

        try (java.sql.PreparedStatement ps =
                conn.prepareStatement(sqlInsert)) {

            ps.setInt(1, idLapangan);
            ps.setString(2, lapangan);
            ps.setString(3, nama);
            ps.setString(4, noHp);
            ps.setDate(5, new java.sql.Date(
                jDateChooser1.getDate().getTime()));
            ps.setDouble(6, total);
            ps.setString(7, metode);
            ps.setDouble(8, dibayar);
            ps.setDouble(9, sisa);

            ps.executeUpdate();

            JOptionPane.showMessageDialog(this,
                "Booking dan pembayaran berhasil disimpan!");

            jTextField1.setText("");
            jTextField2.setText("");
            jDateChooser1.setDate(null);
            textTotal.setText("");
            textDP.setText("");
            textSisa.setText("");
            comboPembayaran.setSelectedIndex(-1);
        }

    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
            "Gagal menyimpan: " + e.getMessage());
    }
    }//GEN-LAST:event_jButton1ActionPerformed

