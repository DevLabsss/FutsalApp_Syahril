private void hitungPembayaran() {
    try {
        double total = Double.parseDouble(
            textTotal.getText().trim()
        );

        if (total <= 0) {
            textDP.setText("");
            textSisa.setText("");
            return;
        }

        String metode = String.valueOf(
            comboPembayaran.getSelectedItem()
        );

        double dibayar;

        if (metode.toLowerCase().contains("dp")) {
            dibayar = total * 0.5;
        } else {
            dibayar = total;
        }

        double sisa = total - dibayar;

        textDP.setText(String.format("%.0f", dibayar));
        textSisa.setText(String.format("%.0f", sisa));

    } catch (NumberFormatException e) {
        textDP.setText("");
        textSisa.setText("");
    }
}


    
private void tampilStatusLapangan() {
    String namaLapangan =
        (String) jComboBox1.getSelectedItem();
        System.out.println("Lapangan dipilih: " + namaLapangan);

    if (namaLapangan == null) {
        lblStatus.setText("");
        return;
    }

    String sql = "SELECT status FROM lapangan "
               + "WHERE nama_lapangan = ?";

    try (java.sql.Connection conn =
            java.sql.DriverManager.getConnection(
                "jdbc:mysql://localhost:3306/db_futsal",
                "root", "");
         java.sql.PreparedStatement ps =
            conn.prepareStatement(sql)) {

        ps.setString(1, namaLapangan);

        try (java.sql.ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                String status = rs.getString("status");
                System.out.println("Status database: " + status);

                lblStatus.setText(
                    "" +
                    (status == null || status.trim().isEmpty()
                        ? "Belum diatur" : status)
                );
            } else {
                lblStatus.setText("Status Lapangan: Tidak ditemukan");
            }
        }

    } catch (java.sql.SQLException e) {
        lblStatus.setText("Status Lapangan: Error");
        System.out.println(e.getMessage());
    }
}


    
    private void tampilNamaLapangan() {
    jComboBox1.removeAllItems();

    String sql = "SELECT nama_lapangan FROM lapangan";

    try (java.sql.Connection conn =
            java.sql.DriverManager.getConnection(
                "jdbc:mysql://localhost:3306/db_futsal",
                "root", "");
         java.sql.PreparedStatement ps =
            conn.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            jComboBox1.addItem(rs.getString("nama_lapangan"));
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Gagal memuat nama lapangan: " + e.getMessage()
        );
    }
}

